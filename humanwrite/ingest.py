"""Main CLI entry point for the humanwrite pipeline.

Usage:
  python -m humanwrite.ingest --rough rough.md --requirements req.md
      --notes notes.md --guidelines guides.md --out out/final.md

Steps:
  1. profile the rough draft -> author_profile.json; generate n candidates
     through the local model and pick the best (tell scan + metric deltas)
  2. humanizer pass (fix AI tells via the local model)
  3. constrain pass (pull back to the rough draft via the local model)
  4. quantitative gate vs the rough draft; up to 3 targeted repair passes
     on failure; write final.md + report.md

The agent (Claude) orchestrates and verifies only: all prose is generated by
the configured local LLM endpoint.
"""

from __future__ import annotations

import argparse
import sys

from humanwrite.config import load_config
from humanwrite.llm import LLMError, client_from_config
from humanwrite.pipeline import run_pipeline


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="humanwrite.ingest",
        description="Turn a human rough draft into a final assignment draft, "
                    "generated entirely by the local LLM endpoint.",
    )
    ap.add_argument("--rough", required=True,
                    help="the human-written rough draft (anchor for voice, "
                         "structure, and errors)")
    ap.add_argument("--requirements", default=None,
                    help="assignment requirements")
    ap.add_argument("--notes", default=None,
                    help="source material in note form (no word cap by default; "
                         "see gate.max_notes_words in config.yaml)")
    ap.add_argument("--guidelines", default=None,
                    help="assignment writing guidelines")
    ap.add_argument("--model", default=None, help="model name (overrides config.yaml)")
    ap.add_argument("--endpoint", default=None,
                    help="LLM endpoint base URL (overrides config.yaml)")
    ap.add_argument("--out", required=True,
                    help="output path for final.md (report.md lands beside it)")
    ap.add_argument("--config", default=None,
                    help="path to config.yaml (default: package config.yaml)")
    ap.add_argument("--quiet", action="store_true", help="less logging")
    args = ap.parse_args(argv)

    cfg = load_config(args.config)
    if args.model:
        cfg["model"] = args.model
    if args.endpoint:
        cfg["endpoint"] = args.endpoint.rstrip("/")

    log = (lambda msg: None) if args.quiet else print
    client = client_from_config(cfg, log=log)
    try:
        result = run_pipeline(
            rough_path=args.rough,
            requirements_path=args.requirements,
            notes_path=args.notes,
            guidelines_path=args.guidelines,
            client=client,
            cfg=cfg,
            out_path=args.out,
            log=log,
        )
    except (ValueError, LLMError) as err:
        print(f"error: {err}", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return 130

    if not result["passed"]:
        print("\ngate FAILED — see report.md for the out-of-band metrics.",
              file=sys.stderr)
        return 3
    print("\ngate passed: final draft written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
